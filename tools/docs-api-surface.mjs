/** Generate the public plugin API inventory from its TypeScript declaration. */
import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
const file='apps/desktop/src/plugins/types.ts';
const source=readFileSync(file,'utf8');
const ast=ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true);
const api=ast.statements.find(node=>ts.isInterfaceDeclaration(node)&&node.name.text==='OnethuApi');
if(!api)throw new Error('OnethuApi declaration not found');
const facade=readFileSync('apps/desktop/src/plugins/facade.ts','utf8');
const gates=new Map([...facade.matchAll(/gate\(perms, "([^"]+)", "([^"]+)"\)/g)].map(match=>[match[2],match[1]]));
const namespaces=[];
for(const member of api.members){
 if(!member.name||!member.type||!ts.isTypeLiteralNode(member.type))continue;
 const namespace=member.name.getText(ast),methods=[];
 function walk(type,prefix=''){
  if(ts.isIntersectionTypeNode(type)){for(const child of type.types)walk(child,prefix);return;}
  if(ts.isFunctionTypeNode(type)){methods.push({name:prefix.replace(/\.$/,''),signature:type.getText(ast),line:ast.getLineAndCharacterOfPosition(type.pos).line+1});return;}
  if(!ts.isTypeLiteralNode(type))return;
  for(const method of type.members){
   if(ts.isMethodSignature(method))methods.push({name:prefix+method.name.getText(ast),signature:method.getText(ast),line:ast.getLineAndCharacterOfPosition(method.getStart(ast)).line+1});
   else if(ts.isPropertySignature(method)&&method.type)walk(method.type,prefix+method.name.getText(ast)+'.');
  }
 }
 walk(member.type);
 for(const method of methods){
  method.signature=method.signature.replace(/\/\*[^]*?\*\//g,'').replace(/\s+/g,' ').trim();
  method.permission=gates.get(namespace+'.'+method.name)??null;
 }
 namespaces.push({namespace,methods});
}
const count=namespaces.reduce((sum,item)=>sum+item.methods.length,0);
const version=JSON.parse(readFileSync('apps/desktop/package.json','utf8')).version;
const json={version,source:file,namespaces: namespaces.length,methods:count,entries:namespaces};
writeFileSync('docs/api-surface.json',JSON.stringify(json,null,2)+'\n');
let md='# 插件 API 完整清单（0.11）\n\n中文 · [English](en/api-surface.md)\n\n> 此表由 `node tools/docs-api-surface.mjs` 从 `OnethuApi` 声明生成。\n\n';
md+=`当前声明包含 **${namespaces.length} 个命名空间、${count} 个方法入口**，含嵌套调用入口。语义、示例与权限模型见 [API 参考](api-reference.md) 和 [插件开发指南](plugin-development.md)。权限列只列出门面中可直接识别的字面量校验；其余方法须结合门面上下文核对，不代表免授权。\n\n`;
md+='接口声明是类型契约；平台能力、当前模式、登录状态和服务端权限仍可能限制实际调用。声明中的复合参数与返回类型按原样保留。\n\n';
for(const {namespace,methods} of namespaces){
 md+=`## ${namespace}\n\n| 调用 | 权限 | 声明 |\n|---|---|---|\n`;
 for(const method of methods)md+=`| \`${namespace}.${method.name}\` | ${method.permission?'`'+method.permission+'`':'见门面实现'} | \`${method.signature.replace(/\|/g,'&#124;')}\` |\n`;
 md+='\n';
}
writeFileSync('docs/api-surface.md',md.trimEnd()+'\n');
console.log(`${namespaces.length} namespaces, ${count} methods`);
let english='# Complete plugin API surface (0.11)\n\n[中文](../api-surface.md) · English\n\n';
english+=`Generated by \`node tools/docs-api-surface.mjs\` from \`OnethuApi\`: **${namespaces.length} namespaces and ${count} method entries**, including nested calls. Type signatures are preserved. The permission column lists only directly recognized literal facade checks. “Inspect facade” does not mean unrestricted access. Platform capability, experience mode, authentication and server permissions can still limit a call. See the [API reference](api-reference.md) and [plugin guide](plugin-development.md).\n\n`;
for(const {namespace,methods} of namespaces){
 english+=`## ${namespace}\n\n| Call | Permission | Declaration |\n|---|---|---|\n`;
 for(const method of methods)english+=`| \`${namespace}.${method.name}\` | ${method.permission?'`'+method.permission+'`':'Inspect facade'} | \`${method.signature.replace(/\|/g,'&#124;')}\` |\n`;
 english+='\n';
}
writeFileSync('docs/en/api-surface.md',english.trimEnd()+'\n');
