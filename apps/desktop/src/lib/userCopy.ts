/**
 * 用户可见文案的「术语净化」出口（b25）。
 *
 * 由来（霖本轮口径）：不要「时不时显示会话超时」这类把人吓一跳的文案——用户只需要知道
 * 「登录状态」，不需要知道「会话 / 凭据 / Cookie」这些内部名词。但原始错误串大量产生在
 * `packages/core`（例如 `SessionExpiredError("网络学堂会话已失效…")`、`AuthRequiredError(
 * "图书馆会话已失效，请重试")`、`YktSessionError("雨课堂会话已失效（HTTP 401）…")`），
 * core 的错误类型与文案是全仓既有契约（多处测试按原文断言），不能也不该在 core 里改。
 *
 * 所以净化只做在**离用户最近的一层**：任何要把上游错误原文直接上屏的地方（设置页的
 * 扩展服务错误条、页面错误条的 `explainNetworkError()` 出口、邮件错误条…）先过一遍
 * `userCopy()`。判定/匹配仍然在原文上做（`isAuthError`、重登判据、日志），不受影响。
 *
 * 这是纯显示层映射：幂等、不抛、不改结构；只换词，不删字。
 *
 * b26 补：core 里残余的「超时」上屏原文——`yuketangQr.ts` 的「等待扫码超时」与
 * core 自身失登判据里的「登录超时 / 登陆超时」——按**已知原文逐条**收口（不是把所有含
 * 「超时」的句子无脑替换）；「网络超时 / 请求超时（Ns 无响应…）」这类真实网络诊断原样保留。
 */
export function userCopy(text: string): string {
  if (!text) return text;
  return (
    text
      // 「会话已超时」→「登录状态已失效」（比「超时」温和，且给出确定性结论）
      .replace(/会话(?:已)?超时/g, "登录状态已失效")
      // b26 补（core 里残余的「超时」上屏原文，逐条对应已知形态，不做泛化替换）：
      // ① `yuketangQr.ts` 长轮询到点未收到扫码 →「等待扫码超时」：用户侧不是「超时」，
      //    而是「还没扫到」，给可操作动作（重新获取二维码）。
      .replace(/等待扫码超时/g, "暂未收到扫码，请重新获取二维码")
      // ② core 自己的失登判据里就有「登录超时 / 登陆超时」（`info/client.ts` 的
      //    isAuthError 正则同值）：它是**认证**超时，不是网络慢，收成登录状态口径。
      //    刻意不碰「网络超时 / 请求超时（30s 无响应…）」这类真实网络诊断（带行动指引）。
      .replace(/登录超时|登陆超时/g, "登录状态已失效")
      // 「会话已失效」→「登录状态已失效」；「会话」其余场合 →「登录状态」
      .replace(/会话/g, "登录状态")
      // 「凭据 / 凭证」→「登录信息」
      .replace(/凭据|凭证/g, "登录信息")
      // 「导入 Cookie」这类指引 → 与设置页按钮同口径「导入登录状态」
      .replace(/\s*Cookie\s*/gi, "登录状态")
  );
}
